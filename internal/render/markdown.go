// Package render provides demiplane's optional, dependency-free markdown→HTML
// rendering. It implements a deliberate *subset* of CommonMark — headings,
// fenced code, lists, blockquotes, horizontal rules, paragraphs, and inline
// code/bold/italic/links — which covers the report-style documents demiplane is
// built to host. It is NOT a complete CommonMark implementation; if richer
// rendering is ever needed, a vetted library can be swapped in behind this same
// Markdown function. All source text is HTML-escaped before inline formatting,
// so raw HTML/JS in the markdown source cannot inject into the rendered page.
package render

import (
	"context"
	"html"
	"regexp"
	"strconv"
	"strings"
	"time"
	"unicode"

	demiplane "github.com/daisandapex/demiplane/v3"
	"github.com/daisandapex/demiplane/v3/internal/theme"
)

// Options controls how Markdown wraps rendered content in a styled document.
// The zero value renders the default house style (theme.Default) with no
// masthead or footer (callers opt into the chrome explicitly).
type Options struct {
	// Theme selects a built-in theme by name (see internal/theme: "light" /
	// "dark"). Empty means "no explicit server theme": the page renders light
	// server-side, and the client toggle's initial state falls back to the OS
	// prefers-color-scheme. A non-empty value is the initial/default theme.
	Theme string
	// CSS, when non-empty, is a complete stylesheet that REPLACES the built-in
	// theme — the --css self-host-branding override. Trusted operator input
	// (a file path the operator chose), injected verbatim into <style>. When
	// set, the client light/dark toggle is disabled (the custom sheet owns the
	// look and need not define both token sets).
	CSS string
	// Title is the fallback document title for the masthead, used when the body
	// has no level-1 heading. Typically the artifact slug.
	Title string
	// Header renders the sticky masthead (document title + theme toggle). When
	// set, the body's first H1 is lifted into the masthead (not duplicated).
	Header bool
	// Footer renders the "Generated by demiplane" vanity footer.
	Footer bool
	// FooterLink is the footer link target; empty renders the wordmark unlinked.
	FooterLink string
	// MetaHeader controls YAML-frontmatter handling. When true, a leading
	// `---`-fenced `key: value` block is lifted out of the body and rendered as a
	// styled meta-header (a localized date/published tstamp plus one labeled line
	// per remaining field) below the masthead title. When false, any frontmatter
	// is stripped and ignored (no header). With no frontmatter, behavior is
	// unchanged either way.
	MetaHeader bool
	// ReplySlug, when non-empty, bakes a first-class inline reply box at the foot
	// of the page (the ?reply=question publish mode). It is the artifact's own
	// (named) slug: the box's JS-free <form> posts to /answer/<slug> — an
	// absolute-path action, so it lands SAME-ORIGIN on the content plane that
	// served the page (scheme inherited → correct once TLS lands). The content
	// plane's submit handler renders a server-truth confirmation, so false success
	// is structurally impossible. A single free-text answer is recorded as a
	// comment-kind reply, fitting Q&A/teaching use. It must be a URL-safe slug (it
	// always is by construction) and is attribute-escaped defensively.
	ReplySlug string
	// ReplyToken is the submission token the reply box carries as a hidden
	// field (internal/formtoken); the reply module refuses a browser
	// submission without a valid one for ReplySlug. Only meaningful with
	// ReplySlug.
	ReplyToken string
	// Colophon, when true, appends the editorial colophon at the foot of the
	// document (demiplane-rwj items 1+2): an optional series prev/next nav row and
	// a meta row (published date · size · link to the instance gallery). Enabled
	// for the ?render=md publish path; the metadata below feeds it.
	Colophon bool
	// Slug is the artifact's own slug — the series family key and the anchor the
	// prev/next order around. Distinct from Title, which the body's first H1 may
	// override; the series computation must key off the stable slug, not the title.
	Slug string
	// Published is the artifact's publish timestamp, shown (date only) in the
	// colophon meta row. It matches the stored CreatedAt (set moments later at Put).
	Published time.Time
	// Siblings lists the slugs of already-published artifacts in the same
	// explicit series (the ?series= publish value), from which prev/next is
	// computed. It excludes the current artifact, which is not yet stored at render
	// time. A family of fewer than two total members renders no nav row (a singleton
	// shows the meta row alone).
	Siblings []string
	// ContentBase is the origin the series prev/next links are minted against (the
	// content plane that serves artifact bodies, ADR 0003). Empty renders the nav
	// slugs unlinked.
	ContentBase string
	// IndexURL is the absolute link for the colophon's "all artifacts →" — the
	// instance gallery on the control plane, honoring the base-URL convention so it
	// stays instance-portable. Empty omits the link.
	IndexURL string
	// ReplyNext, when non-empty (only meaningful with ReplySlug), names the
	// FOLLOW-UP slug the student flows to after answering — the ?next= publish
	// param. It travels as a hidden form field; after a recorded answer the
	// confirmation page waits for this slug to be published and then carries the
	// student there. Validated at publish (slug-shaped, ≠ ReplySlug) and
	// re-validated at submit (a hidden field is client-tamperable).
	ReplyNext string
	// Limits bounds the render; zero fields take DefaultLimits.
	Limits Limits
}

var (
	reHeading = regexp.MustCompile(`^(#{1,6})\s+(.*)$`)
	reOrdered = regexp.MustCompile(`^\d+\.\s+(.*)$`)
	reHRule   = regexp.MustCompile(`^(-{3,}|\*{3,}|_{3,})$`)
	// reTableSep matches a GFM table separator row, e.g. |---|:--:|--:| (with
	// optional alignment colons), so a preceding pipe row is treated as a header.
	reTableSep = regexp.MustCompile(`^\s*\|?\s*:?-+:?\s*(\|\s*:?-+:?\s*)*\|?\s*$`)

	// reTag matches an HTML tag, for reducing inline-rendered title HTML to the
	// plain text an element <title> needs.
	reTag = regexp.MustCompile(`<[^>]*>`)

	// Inline patterns, applied to already-escaped text.
	reCode   = regexp.MustCompile("`([^`]+)`")
	reLink   = regexp.MustCompile(`\[([^\]]+)\]\(([^)\s]+)\)`)
	reBold   = regexp.MustCompile(`\*\*([^*]+)\*\*`)
	reItalic = regexp.MustCompile(`\*([^*]+)\*`)
	// Underscore emphasis requires a word boundary on both sides (CommonMark
	// 6.2: `_` is left-flanking only when not preceded by an alphanumeric), so
	// intraword underscores — snake_case identifiers in prose — stay literal.
	// `_` is itself a word character to RE2, so `\b_` means "preceded by a
	// non-word character or the start", and `_\b` the mirror on the right.
	reItalicU = regexp.MustCompile(`\b_([^_]+)_\b`)
)

// Render renders src as a complete, styled HTML document (used for the
// ?render=md publish path). opts selects the theme/custom stylesheet and the
// optional masthead + footer chrome; the design tokens and typography are the
// same the /docs pages use, shared via internal/theme.
//
// The render is bounded by opts.Limits (see budget.go): a document that would
// exceed a limit is rejected with an error matching ErrBudget, never
// truncated. It stops with the context's error once ctx is done.
func Render(ctx context.Context, src []byte, opts Options) ([]byte, error) {
	st := newState(ctx, opts.Limits.withDefaults())
	if err := st.ctxErr(); err != nil {
		return nil, err
	}
	// The render holds one string copy of the input (two while CRLF is
	// folded) and reads every line out of it by offset.
	text := string(src)
	if strings.Contains(text, "\r\n") {
		text = strings.ReplaceAll(text, "\r\n", "\n")
	}
	l, err := splitLines(st, text)
	if err != nil {
		return nil, err
	}

	// Frontmatter: a leading `---`-fenced key:value block. When the meta-header is
	// on we render it below the title; when off (or always, if it's there) we
	// strip it so the raw fence never leaks into the body. No frontmatter → no-op.
	from := 0
	var metaHTML string
	var metaNeedsScript bool
	if close := frontmatterEnd(l); close > 0 {
		from = close + 1
		if opts.MetaHeader {
			fields, err := parseFrontmatter(st, l, close)
			if err != nil {
				return nil, err
			}
			if metaHTML, metaNeedsScript, err = metaHeader(st, fields); err != nil {
				return nil, err
			}
		}
	}

	// The masthead shows the document title; lifting the first H1 into it avoids
	// a duplicate giant title in the body. Without a header, the H1 stays put.
	title := html.EscapeString(opts.Title)
	if opts.Header {
		h1, line, err := firstH1(st, l, from)
		if err != nil {
			return nil, err
		}
		if line >= 0 {
			title, l.hole = h1, line
		}
	}
	if title == "" {
		title = "Untitled"
	}
	// titleText is the plain-text form for the <head><title>: the masthead title
	// may carry inline markup (a lifted H1 rendered <code>/<em>/<a>), which is
	// inert in an element title, so strip tags. Entities stay escaped.
	titleText := stripTags(title)

	// Stylesheet: a --css override owns the look (toggle off); a pinned named
	// theme (catppuccin/dracula/one-dark) fixes its single palette (toggle off,
	// nothing to flip to); otherwise EVERY rendered document ships the
	// three-block contract sheet (light on bare :root, dark under a guarded
	// prefers-color-scheme media query, dark again under an explicit
	// [data-theme="dark"]), so the OS preference and a stored choice work even
	// on pages without the masthead toggle. An unknown theme name falls back to
	// "" (the default light face of the contract).
	themeName := opts.Theme
	if themeName != "" && !theme.Valid(themeName) {
		themeName = ""
	}
	contract := opts.CSS == "" && !theme.Pinned(themeName)
	toggle := contract && opts.Header
	var css string
	switch {
	case opts.CSS != "":
		css = opts.CSS
	case contract:
		css = theme.ToggleCSS()
	default:
		css = theme.CSS(themeName)
	}
	if opts.Header || opts.Footer {
		css += docChromeCSS
	}
	if metaHTML != "" {
		css += metaHeadCSS
	}
	if opts.ReplySlug != "" {
		css += replyBoxCSS
	}
	if opts.Colophon {
		css += coloCSS
	}
	// The print sheet forces a page-friendly light palette and unsticks the
	// chrome regardless of the on-screen theme. Skip it only when the operator
	// supplied a full --css override (their sheet owns print too).
	if opts.CSS == "" {
		css += printCSS
	}

	// Masthead pages take the F layout (flayout.go): the facts move from the
	// column into the rail, and a series family gets the tree. A --css sheet
	// owns the look, so its pages keep the plain masthead and single column;
	// F would hand an operator's sheet a grid, rail and tree it never styled.
	fLayout := opts.Header && opts.CSS == ""
	// A series past the member cap renders as no series: no tree, no prev/next.
	if len(opts.Siblings)+1 > st.lim.MaxSeriesMembers {
		opts.Siblings = nil
	}
	// The body tags its own lead paragraph (the dek) and, on F pages, the
	// paragraphs that open with inline code, and collects the outline as it
	// writes headings, so no finished HTML is rewritten or rescanned.
	st.lead = opts.Header
	st.codeFirst = fLayout
	st.collectOutline = fLayout
	body := st.newOut()
	if err := renderBlocks(st, l, from, body); err != nil {
		return nil, err
	}
	if opts.Header && !fLayout {
		css += mastheadCSS
	}
	var rail, tree, bodyClass string
	if fLayout {
		css += fCSS + fPrintCSS
		rail, err = railHTML(st, metaHTML, st.outline)
		if err != nil {
			return nil, err
		}
		if metaHTML != "" {
			css += fMetaCSS
		}
		metaHTML = "" // it lives in the rail now
		if fam := seriesFamily(opts.Slug, opts.Siblings); fam != nil {
			if tree, err = treeHTML(st, opts.Slug, fam, opts.ContentBase); err != nil {
				return nil, err
			}
		}
		bodyClass = "f"
		if tree != "" {
			bodyClass += " has-tree"
		}
		if rail != "" {
			bodyClass += " has-rail"
		}
	}

	// The page is a list of parts. Chrome is charged as it is added; the body,
	// meta-header and rail were charged as they were written. The parts are
	// copied once, into the finished document.
	pg := page{st: st}
	pg.add(docHead(css, titleText, themeName, contract, toggle, bodyClass))
	switch {
	case fLayout:
		pg.add(topbar(themeName, toggle, tree != ""))
		pg.add(`<div class="fgrid">` + "\n")
		pg.keep(tree)
		pg.add(`<header class="dochead"><h1 class="doctitle">` + title + "</h1></header>\n")
	case opts.Header:
		pg.add(masthead(title, themeName, toggle))
	}
	pg.add("<main class=\"wrap\">\n")
	pg.keep(metaHTML)
	pg.keep(body.String())
	if opts.ReplySlug != "" {
		pg.add(replyBox(opts.ReplySlug, opts.ReplyNext, opts.ReplyToken))
	}
	if opts.Colophon {
		pg.colophon = len(pg.parts)
		pg.add(colophon(opts))
	}
	pg.add("</main>\n")
	if fLayout {
		pg.keep(rail)
		pg.add("</div>\n")
	}
	if opts.Footer {
		if fLayout {
			pg.add(`<footer class="docfoot"><div class="wrap"><div class="fcell">` +
				footerInner(opts.FooterLink) + "</div></div></footer>\n")
		} else {
			pg.add(footerHTML(opts.FooterLink))
		}
	}
	if opts.Header {
		pg.add(docChromeScript)
	}
	if fLayout {
		pg.add(fScript)
	}
	if metaNeedsScript {
		pg.add(tstampScript)
	}
	pg.add(docTail)
	return pg.finish()
}

// page collects a rendered document's parts in order.
type page struct {
	st       *state
	parts    []string
	colophon int // index of the colophon part (it carries the size), or 0
}

// add appends chrome, charging it to the budget.
func (p *page) add(s string) {
	if s != "" && p.st.charge(len(s)) == nil {
		p.parts = append(p.parts, s)
	}
}

// keep appends a part an out already charged.
func (p *page) keep(s string) {
	if s != "" {
		p.parts = append(p.parts, s)
	}
}

// finish copies the parts into the document, in one allocation of its exact
// size. The colophon's size sentinel is resolved against the finished length,
// the exact byte count the store will record for this artifact: the length
// with the sentinel removed, plus the length of the size string itself.
func (p *page) finish() ([]byte, error) {
	if p.st.err != nil {
		return nil, p.st.err
	}
	total := 0
	for _, s := range p.parts {
		total += len(s)
	}
	size, at := "", -1
	if p.colophon > 0 && p.colophon < len(p.parts) {
		if i := strings.Index(p.parts[p.colophon], sizeSentinel); i >= 0 {
			base := total - len(sizeSentinel)
			size = humanSize(int64(base))
			size = humanSize(int64(base + len(size))) // one refinement for the number's own bytes
			total, at = base+len(size), i
		}
	}
	if err := p.st.output(total); err != nil {
		return nil, err
	}
	doc := make([]byte, 0, total)
	for k, s := range p.parts {
		if k == p.colophon && at >= 0 {
			doc = append(doc, s[:at]...)
			doc = append(doc, size...)
			doc = append(doc, s[at+len(sizeSentinel):]...)
			continue
		}
		doc = append(doc, s...)
	}
	return doc, nil
}

// firstH1 finds the document's first level-1 heading at or after line from,
// ignoring headings inside fenced code, and returns its inline-rendered text
// and raw line index (-1 when there is none). The heading is held to the
// output budget before it is formatted.
func firstH1(st *state, l *lines, from int) (titleHTML string, line int, err error) {
	inFence := false
	for i := from; i < l.rawLen(); i++ {
		if err := st.tick(); err != nil {
			return "", -1, err
		}
		t := strings.TrimSpace(l.raw(i))
		if strings.HasPrefix(t, "```") {
			inFence = !inFence
			continue
		}
		if inFence {
			continue
		}
		if m := reHeading.FindStringSubmatch(t); m != nil && len(m[1]) == 1 {
			if err := st.inlineFits(m[2]); err != nil {
				return "", -1, err
			}
			return inline(m[2]), i, nil
		}
	}
	return "", -1, nil
}

// masthead renders the plain sticky title bar a --css page keeps in place of
// the F top bar: a kicker (the wordmark, small-caps and accented), the document
// title set as the page's single display-serif H1, and, when toggle is set, the
// light/dark toggle. The toggle carries both a sun and a moon SVG; CSS shows the
// one matching data-theme. Under --css toggle is always false today; the
// parameter keeps the two bars' signatures alike.
func masthead(titleHTML, serverTheme string, toggle bool) string {
	var b strings.Builder
	b.WriteString(`<header class="docbar"><div class="wrap"><div class="masthead">`)
	b.WriteString(`<span class="kicker">demiplane</span>`)
	b.WriteString(`<h1 class="doctitle">` + titleHTML + `</h1>`)
	b.WriteString(`</div>`)
	if toggle {
		pressed := "false"
		if serverTheme == "dark" {
			pressed = "true"
		}
		b.WriteString(`<button class="themetoggle" type="button" aria-pressed="` + pressed + `" ` +
			`aria-label="Toggle light or dark theme" title="Toggle theme">` +
			sunSVG + moonSVG + `</button>`)
	}
	b.WriteString("</div></header>\n")
	return b.String()
}

// stripTags reduces inline-rendered HTML to its text content by removing tags.
// Used to derive the element <title> from a masthead title that may carry inline
// markup; HTML entities in the text are left escaped (valid title content).
func stripTags(s string) string { return reTag.ReplaceAllString(s, "") }

// headingText reduces a heading's raw markdown to the plain text used for its
// slug id and permalink aria-label: it runs the same inline pipeline the body
// uses (so [text](url) collapses to "text", `code` to "code", **bold** to
// "bold"), strips the resulting tags, and unescapes entities back to literal
// text. slugify then keeps only [a-z0-9-], and the aria-label re-escapes for the
// attribute, so no unescaped source can reach either sink.
func headingText(raw string) string {
	return html.UnescapeString(stripTags(inline(raw)))
}

// slugify builds a URL-safe fragment id from heading text: lowercased, runs of
// whitespace or existing hyphens collapse to a single hyphen, every other
// character (punctuation, entities, non-ASCII) is dropped, and leading/trailing
// hyphens are trimmed. The output is drawn from [a-z0-9-] only, so it is safe to
// interpolate into both an id attribute and an href fragment without escaping.
// It stops at maxSlugLen bytes: an id is repeated in the heading, its anchor
// and the outline, so its length must not follow the heading's.
func slugify(s string) string {
	var b strings.Builder
	prevHyphen := false
	for _, r := range s {
		// Per rune, so lowering never builds a copy of s (lowercasing can
		// lengthen UTF-8 text).
		r = unicode.ToLower(r)
		switch {
		case b.Len() >= maxSlugLen:
			return strings.TrimRight(b.String(), "-")
		case (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9'):
			b.WriteRune(r)
			prevHyphen = false
		case r == ' ' || r == '\t' || r == '-' || r == '_':
			if b.Len() > 0 && !prevHyphen {
				b.WriteByte('-')
				prevHyphen = true
			}
		}
	}
	return strings.TrimRight(b.String(), "-")
}

// maxSlugLen caps a heading id built from its text.
const maxSlugLen = 64

// slugger hands out heading ids that are unique within one document:
// slugify(text), with a numeric suffix (-1, -2, ...) on collision. Every id
// handed out is recorded (including the suffixed forms), so a later natural
// "foo-1" heading cannot duplicate a generated one. An empty slug (a heading
// of only punctuation or emoji) falls back to "section". Deterministic for a
// given heading sequence.
//
// next remembers, per base, the lowest suffix that may still be free: every
// smaller suffix was either handed out or found taken, and ids are never
// released, so resuming there yields the same id a search from 1 would. A
// candidate "base-i" belongs to exactly one base (the text before its last
// hyphen), so each taken id is skipped at most once and the total work is
// linear in the number of headings.
type slugger struct {
	used map[string]bool
	next map[string]int
}

func newSlugger() slugger {
	return slugger{used: map[string]bool{}, next: map[string]int{}}
}

func (sg slugger) unique(text string) string {
	base := slugify(text)
	if base == "" {
		base = "section"
	}
	s := base
	if sg.used[s] {
		i := sg.next[base]
		if i == 0 {
			i = 1
		}
		for {
			s = base + "-" + strconv.Itoa(i)
			if !sg.used[s] {
				break
			}
			if workProbe != nil {
				workProbe(1)
			}
			i++
		}
		sg.next[base] = i + 1
	}
	sg.used[s] = true
	return s
}

// headingAnchor renders the quiet hover-'#' permalink placed at the end of every
// rendered heading. It links to the heading's own fragment and carries an
// aria-label ("Permalink to <heading>") for assistive tech. id is slug-safe by
// construction; plain is attribute-escaped. The affordance is hidden until the
// heading is hovered or the link is focused (see contentCSS .heading-anchor), and
// reserves its own space so revealing it shifts no layout.
func headingAnchor(id, plain string) string {
	return `<a class="heading-anchor" href="#` + id +
		`" aria-label="Permalink to ` + html.EscapeString(plain) + `">#</a>`
}

// sunSVG / moonSVG are crisp inline stroke icons (currentColor, no external
// dep). docChromeCSS shows exactly one per theme via the data-theme attribute.
const sunSVG = `<svg class="i-sun" viewBox="0 0 24 24" aria-hidden="true" focusable="false" ` +
	`fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round">` +
	`<circle cx="12" cy="12" r="4.1"/>` +
	`<path d="M12 2.6v2.1M12 19.3v2.1M2.6 12h2.1M19.3 12h2.1M5.1 5.1l1.5 1.5M17.4 17.4l1.5 1.5M18.9 5.1l-1.5 1.5M6.6 17.4l-1.5 1.5"/></svg>`

const moonSVG = `<svg class="i-moon" viewBox="0 0 24 24" aria-hidden="true" focusable="false" ` +
	`fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">` +
	`<path d="M20.5 14.3A8.2 8.2 0 0 1 9.7 3.5a8.2 8.2 0 1 0 10.8 10.8z"/></svg>`

// footerHTML renders the thin vanity footer, aligned to the text column. The
// link is operator-controlled (config, trusted) but still attribute-escaped. An
// empty link renders the wordmark unlinked.
func footerHTML(link string) string {
	return `<footer class="docfoot"><div class="wrap">` + footerInner(link) + "</div></footer>\n"
}

// footerInner is the footer's text, shared by the plain and the F footer.
func footerInner(link string) string {
	mark := `<span class="mark">demiplane</span>`
	if link != "" {
		mark = `<a href="` + html.EscapeString(link) + `" rel="noopener noreferrer" class="mark">demiplane</a>`
	}
	return "Generated by " + mark
}

// replyBox renders the first-class inline reply box baked at the foot of a
// ?reply=question page, targeting slug's same-origin submit endpoint. Design
// invariants that make false success impossible:
//
//   - Absolute-path action (/answer/<slug>): the form posts to the content origin
//     that served the page — same-origin by construction, no cross-origin/mixed-
//     content failure, and correct once TLS lands (the scheme is inherited, not
//     hard-coded). The slug is attribute-escaped.
//   - No JavaScript: the browser navigates to the server's real response. The
//     "recorded" confirmation is server-rendered ONLY after the answer persists;
//     a failed write renders an honest error, never a success. Contrast the
//     dogfood incident's onsubmit timer that claimed success unconditionally.
//   - required textarea: a courtesy client-side guard; the server re-validates a
//     non-empty answer regardless.
//   - next (the ?next= publish param) rides along as a hidden field so the
//     server-rendered confirmation can flow the student to the follow-up lesson.
//     Hidden fields are client-tamperable, so the submit handler re-validates it;
//     it only ever produces a same-origin, slug-shaped link.
