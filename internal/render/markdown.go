// Body renders src to inner HTML only (no <html>/<head> wrapper), so callers
// such as the /docs route can place it inside their own page chrome while
// reusing this single markdown engine.
//
// Body is for trusted, operator-shipped documents and applies no limits; the
// publish path uses Render.
func Body(src []byte) string {
	st := newState(context.Background(), unlimited)
	l, err := splitLines(st, strings.ReplaceAll(string(src), "\r\n", "\n"))
	if err != nil {
		return ""
	}
	o := st.newOut()
	_ = renderBlocks(st, l, 0, o)
	return o.String()
}

// textRun accumulates the lines of one inline block (a paragraph, a quote, a
// list item's paragraph) joined by spaces, holding the formatted size of the
// whole run to the remaining output budget as each line arrives, so the run is
// never longer than the budget allows it to render to.
type textRun struct {
	st    *state
	b     strings.Builder
	n     int // lines in the run
	upper int // inlineUpper of the run
}

// slack covers the tags a block adds around its inline text.
const slack = 64

func (r *textRun) add(s string) error {
	u := inlineUpper(s) + 1
	if err := r.st.fits(r.upper + u + slack); err != nil {
		return err
	}
	if r.n > 0 {
		r.b.WriteByte(' ')
	}
	r.b.WriteString(s)
	r.n++
	r.upper += u
	return nil
}

// take returns the run's text and empties it.
func (r *textRun) take() string {
	s := r.b.String()
	r.b.Reset()
	r.n, r.upper = 0, 0
	return s
}

func (r *textRun) empty() bool { return r.n == 0 }

// renderBlocks converts markdown block structure to HTML, from line from on,
// writing into o. Heading ids come from st.slugs, scoped per render, so ids
// are stable for a given source and independent across documents.
func renderBlocks(st *state, l *lines, from int, o *out) error {
	para := textRun{st: st}

	flushPara := func() {
		if para.empty() {
			return
		}
		h := inline(para.take())
		var cls string
		if st.lead && st.blocks == 0 {
			cls = "lead"
		}
		if st.codeFirst && strings.HasPrefix(h, "<code>") {
			cls = strings.TrimSpace(cls + " code-first")
		}
		if cls == "" {
			o.WriteString("<p>")
		} else {
			o.WriteString(`<p class="` + cls + `">`)
		}
		o.WriteString(h)
		o.WriteString("</p>\n")
		st.blocks++
	}

	n := l.n()
	for i := from; i < n; i++ {
		// Every write is charged as it happens; the first refusal is sticky
		// and ends the render here. The context is checked as lines are
		// consumed.
		if st.err != nil {
			return st.err
		}
		if err := st.tick(); err != nil {
			return err
		}
		line := l.at(i)
		trimmed := strings.TrimSpace(line)

		switch {
		case strings.HasPrefix(trimmed, "```"):
			flushPara()
			// The fence info-string names the language (```go); its first token
			// selects the syntax highlighter (highlight.go). Collect until close.
			// The code is held to the remaining budget as it is collected (its
			// escaped output is never shorter than it).
			lang := strings.TrimSpace(trimmed[3:])
			var code strings.Builder
			first := true
			for i++; i < n && !strings.HasPrefix(strings.TrimSpace(l.at(i)), "```"); i++ {
				if err := st.tick(); err != nil {
					return err
				}
				ln := l.at(i)
				if err := st.fits(code.Len() + len(ln) + 1); err != nil {
					return err
				}
				if !first {
					code.WriteByte('\n')
				}
				first = false
				code.WriteString(ln)
			}
			o.WriteString("<pre><code")
			if canon := canonLang(lang); canon != "" {
				o.WriteString(` class="language-` + canon + `"`)
			}
			o.WriteString(">")
			// highlight() escapes every byte it emits (classed span or plain run);
			// an unsupported language returns the source HTML-escaped and unstyled,
			// so the raw-HTML-in-code XSS guard holds either way. It counts its
			// output before building it and stops at the remaining budget.
			codeHTML, err := highlightTo(st, st.remaining(), lang, code.String())
			if err != nil {
				return err
			}
			code.Reset()
			o.WriteString(codeHTML)
			o.WriteString("</code></pre>\n")
			st.blocks++

		case trimmed == "":
			flushPara()

		case reHRule.MatchString(trimmed):
			flushPara()
			o.WriteString("<hr>\n")
			st.blocks++

		case reHeading.MatchString(trimmed):
			flushPara()
			m := reHeading.FindStringSubmatch(trimmed)
			// The heading text appears twice (the heading and its anchor's
			// label), with an id of at most maxSlugLen bytes twice and fixed
			// markup; all of it is held to the budget before any is built.
			if err := st.fits(2*inlineUpper(m[2]) + 2*maxSlugLen + 128); err != nil {
				return err
			}
			if st.headings++; st.headings > st.lim.MaxHeadings {
				return st.limit("headings", st.lim.MaxHeadings)
			}
			level := len(m[1])
			h := inline(m[2])
			plain := html.UnescapeString(stripTags(h)) // headingText(m[2])
			id := st.slugs.unique(plain)
			lvl := string(rune('0' + level))
			o.WriteString("<h" + lvl + ` id="` + id + `">`)
			o.WriteString(h)
			o.WriteString(headingAnchor(id, plain))
			o.WriteString("</h" + lvl + ">\n")
			if st.collectOutline && (level == 2 || level == 3) {
				st.outline = append(st.outline, outlineItem{level: level, id: id, text: stripTags(h)})
			}
			st.blocks++

		case strings.HasPrefix(trimmed, "> "):
			flushPara()
			// Consume prefixed lines plus lazy continuation: a wrapped quote line
			// without the `> ` prefix joins the quote, ending on a blank line, a
			// list marker, or a block opener — the same paragraph-interruption
			// rules the list continuation uses.
			quote := textRun{st: st}
			for i < n {
				if err := st.tick(); err != nil {
					return err
				}
				qt := strings.TrimSpace(l.at(i))
				var piece string
				if strings.HasPrefix(qt, "> ") {
					piece = strings.TrimPrefix(qt, "> ")
				} else if qt != "" && !isUnordered(qt) && !reOrdered.MatchString(qt) &&
					!interruptsParagraph(qt) {
					piece = qt
				} else {
					break
				}
				if err := quote.add(piece); err != nil {
					return err
				}
				i++
			}
			i--
			o.WriteString("<blockquote>")
			o.WriteString(inline(quote.take()))
			o.WriteString("</blockquote>\n")
			st.blocks++

		case isUnordered(trimmed) || reOrdered.MatchString(trimmed):
			flushPara()
			next, err := renderList(st, l, i, o)
			if err != nil {
				return err
			}
			i = next - 1
			st.blocks++

		case strings.Contains(trimmed, "|") && i+1 < n && reTableSep.MatchString(l.at(i+1)):
			// GFM pipe table: header row, |---| separator, then body rows until a
			// blank or non-pipe line.
			//
			// The width is counted before the header is split, and every body row
			// is admitted against the document's cell budget at that width (rows
			// are padded to it) and against the remaining output budget, at its
			// padded size, before it is split. Rows are written as they are read.
			flushPara()
			cols := countCells(trimmed)
			if err := st.tableColumns(cols); err != nil {
				return err
			}
			if err := st.inlineFits(trimmed); err != nil {
				return err
			}
			header := splitCells(trimmed, cols)
			o.WriteString(`<div class="table-wrap">` + "\n")
			o.WriteString("<table>\n<thead><tr>")
			for _, h := range header {
				o.WriteString("<th>" + h + "</th>")
			}
			o.WriteString("</tr></thead>\n<tbody>\n")
			i += 2 // consume header + separator; i now at the first body row
			for i < n {
				lt := strings.TrimSpace(l.at(i))
				if lt == "" || !strings.Contains(lt, "|") {
					break
				}
				if err := st.tick(); err != nil {
					return err
				}
				if err := st.tableRow(cols); err != nil {
					return err
				}
				if err := st.fits(inlineUpper(lt) + len("<td></td>")*len(header) + len("<tr></tr>\n")); err != nil {
					return err
				}
				cells := splitCells(lt, cols)
				o.WriteString("<tr>")
				for c := range header {
					cell := ""
					if c < len(cells) {
						cell = cells[c]
					}
					o.WriteString("<td>" + cell + "</td>")
				}
				o.WriteString("</tr>\n")
				i++
			}
			i-- // the outer loop's i++ advances past the last consumed row
			o.WriteString("</tbody>\n</table>\n</div>\n")
			st.blocks++

		default:
			if err := para.add(trimmed); err != nil {
				return err
			}
		}
	}
	flushPara()
	return st.err
}

func isUnordered(s string) bool {
	return strings.HasPrefix(s, "- ") || strings.HasPrefix(s, "* ") || strings.HasPrefix(s, "+ ")
}

// interruptsParagraph reports whether a trimmed line is a block opener that (per
// CommonMark) can interrupt a paragraph — and so ends lazy continuation instead
// of joining the current item or quote.
func interruptsParagraph(trimmed string) bool {
	return reHeading.MatchString(trimmed) || reHRule.MatchString(trimmed) ||
		strings.HasPrefix(trimmed, "```") || strings.HasPrefix(trimmed, "> ")
}

// renderList consumes a run of list items starting at line start and renders
// it to nested <ul>/<ol> HTML into o, returning the index of the first line
// past the list. A run is ended by a blank line NOT followed by an indented
// continuation paragraph, or by a block opener (heading, hrule, fence,
// blockquote).
//
// Continuation (CommonMark lazy continuation): a non-blank line that is not a
// list marker and not a block opener joins the current item's content with a
// space — regardless of indent, so hard-wrapped items (authors wrap at 72-80
// columns) render as one <li>. A blank line followed by a line indented past the
// current item's marker opens a further paragraph inside the same <li> (a loose
// item renders every one of its paragraphs in <p>); a blank line followed by
// anything else ends the list.
//
// Nesting is driven by leading indentation (the house convention is two spaces
// per level, but any consistent widening nests and any narrowing closes, so
// deeper or ragged indentation still yields a valid tree), up to st's
// MaxListDepth. Ordered and unordered items mix freely: a change of marker kind
// at the same indent closes the current list and opens the other. Item text
// runs through inline(), which HTML-escapes before formatting, so the
// escape-first XSS posture is unchanged. Fenced code inside a list item is a
// known gap (out of scope for this fix).
//
// Invariant: each open list frame always has exactly one <li> whose </li> is
// deferred until a sibling replaces it, a child list closes above it, or the run
// unwinds — which is what lets a nested list live inside its parent's still-open
// <li>.
//
// Item text is held to the remaining budget as it is read (textRun). Only the
// current paragraph is held: once an item turns out to be loose, each of its
// paragraphs is written in <p> as soon as the next one starts.
func renderList(st *state, l *lines, start int, o *out) (int, error) {
	type frame struct {
		indent  int
		ordered bool
	}
	var stack []frame
	cur := textRun{st: st} // the current item's open paragraph
	open := false          // whether an item is open (its text not yet written)
	loose := false         // whether the open item has more than one paragraph

	openTag := func(ordered bool) {
		if ordered {
			o.WriteString("<ol>\n")
		} else {
			o.WriteString("<ul>\n")
		}
	}
	closeTag := func(ordered bool) {
		if ordered {
			o.WriteString("</ol>\n")
		} else {
			o.WriteString("</ul>\n")
		}
	}
	// endPara writes the open item's completed paragraph in <p>.
	endPara := func() {
		o.WriteString("<p>" + inline(cur.take()) + "</p>")
	}
	// flushItem writes the current item's remaining content: a tight single
	// paragraph renders bare, a loose item's last paragraph in <p>.
	flushItem := func() {
		if !open {
			return
		}
		if loose {
			endPara()
		} else {
			o.WriteString(inline(cur.take()))
		}
		open, loose = false, false
	}

	n := l.n()
	i := start
	for i < n {
		if st.err != nil {
			return 0, st.err
		}
		if err := st.tick(); err != nil {
			return 0, err
		}
		raw := l.at(i)
		trimmed := strings.TrimSpace(raw)

		if trimmed == "" {
			// Blank line: a following line indented past the current item's marker
			// (and not itself a marker) continues the item as a new paragraph;
			// anything else ends the list.
			if j := i + 1; j < n && len(stack) > 0 {
				next := l.at(j)
				nt := strings.TrimSpace(next)
				nindent := len(next) - len(strings.TrimLeft(next, " \t"))
				if nt != "" && !isUnordered(nt) && !reOrdered.MatchString(nt) &&
					!interruptsParagraph(nt) && nindent > stack[len(stack)-1].indent {
					endPara()
					loose, open = true, true
					i++
					continue
				}
			}
			break
		}

		ordered := reOrdered.MatchString(trimmed)
		unordered := isUnordered(trimmed)
		if !ordered && !unordered {
			if len(stack) == 0 || interruptsParagraph(trimmed) {
				break
			}
			// Lazy continuation: join the current item's paragraph.
			if err := cur.add(trimmed); err != nil {
				return 0, err
			}
			open = true
			i++
			continue
		}

		indent := len(raw) - len(strings.TrimLeft(raw, " \t"))
		var content string
		if ordered {
			content = reOrdered.FindStringSubmatch(trimmed)[1]
		} else {
			content = trimmed[2:]
		}

		// A new marker ends the current item's content region.
		flushItem()

		// Ascend: close every level deeper than this item's indent. Each pop closes
		// that level's open <li> and its list tag; the parent <li> it lived inside is
		// closed by the next shallower iteration (or by the sibling/unwind below).
		for len(stack) > 0 && indent < stack[len(stack)-1].indent {
			o.WriteString("</li>\n")
			closeTag(stack[len(stack)-1].ordered)
			stack = stack[:len(stack)-1]
		}

		if len(stack) > 0 && indent == stack[len(stack)-1].indent {
			// Sibling at the same level: close the previous item, then reopen as the
			// other marker kind if this item switched ordered<->unordered.
			o.WriteString("</li>\n")
			if stack[len(stack)-1].ordered != ordered {
				closeTag(stack[len(stack)-1].ordered)
				stack = stack[:len(stack)-1]
				openTag(ordered)
				stack = append(stack, frame{indent: indent, ordered: ordered})
			}
		} else {
			// Deeper than the current top (or the very first item): open a new list.
			// When deeper, it nests inside the parent's still-open <li>.
			if len(stack) >= st.lim.MaxListDepth {
				return 0, st.limit("list depth", st.lim.MaxListDepth)
			}
			openTag(ordered)
			stack = append(stack, frame{indent: indent, ordered: ordered})
		}

		o.WriteString("<li>")
		if err := cur.add(content); err != nil {
			return 0, err
		}
		open = true
		i++
	}
	flushItem()
	if st.err != nil {
		return 0, st.err
	}

	// Unwind any levels left open at the end of the run.
	for len(stack) > 0 {
		o.WriteString("</li>\n")
		closeTag(stack[len(stack)-1].ordered)
		stack = stack[:len(stack)-1]
	}
	return i, st.err
}

// rowInner strips a table row's surrounding whitespace and its leading and
// trailing pipe.
func rowInner(row string) string {
	s := strings.TrimSpace(row)
	s = strings.TrimPrefix(s, "|")
	return strings.TrimSuffix(s, "|")
}

// countCells returns how many cells splitCells would find in row, without
// allocating them.
func countCells(row string) int {
	return strings.Count(rowInner(row), "|") + 1
}

// splitCells splits a GFM table row into at most max inline-rendered cells.
// Leading and trailing pipes are stripped; cells past max are dropped (a body
// row is truncated to the header width anyway) without being split or
// rendered. Each cell goes through inline(), which escapes before formatting,
// so cell content (including raw HTML) cannot inject.
func splitCells(row string, max int) []string {
	parts := strings.SplitN(rowInner(row), "|", max+1)
	if len(parts) > max {
		parts = parts[:max]
	}
	cells := make([]string, len(parts))
	for i, p := range parts {
		cells[i] = inline(strings.TrimSpace(p))
	}
	return cells
}

// codeSentinel frames a code-span placeholder. NUL cannot survive
// html.EscapeString'd source text, so a framed index is unambiguous — the same
// placeholder shape highlight.go uses for escaping.
const codeSentinel = "\x00"

// workProbe, when set by a test, is told how much work the slug and code-span
// passes do, so their growth can be checked without timing.
var workProbe func(n int)

// inline escapes text and applies inline formatting. Escaping happens first so
// raw HTML in the source is rendered as text, never executed. Code spans are
// then lifted into placeholders BEFORE the emphasis passes run, so `_`/`*`
// inside inline code (most snake_case identifiers) are never rewritten into
// <em>/<strong>; the finished spans are restored last.
//
// Every pass builds one string no longer than the result (inlineUpper bounds
// it); per match, the code-span pass records two offsets and the link pass
// reads its parts by index, so the work kept per construct is a few bytes.
func inline(s string) string {
	// NUL is the placeholder frame and html.EscapeString leaves it alone, so a
	// source NUL becomes U+FFFD (as CommonMark replaces it) before the
	// placeholders are cut.
	if strings.IndexByte(s, 0) >= 0 {
		s = strings.ReplaceAll(s, "\x00", "\uFFFD")
	}
	esc := html.EscapeString(s)
	s, spans := liftCodeSpans(esc)
	s = reLink.ReplaceAllStringFunc(s, renderLink)
	s = reBold.ReplaceAllString(s, "<strong>$1</strong>")
	s = reItalic.ReplaceAllString(s, "<em>$1</em>")
	s = reItalicU.ReplaceAllString(s, "<em>$1</em>")
	return restoreSpans(s, esc, spans)
}

// span is a code span's content, as offsets into the escaped text.
type span struct{ start, end int32 }

// liftCodeSpans replaces each code span of esc (the reCode shape: a backtick,
// one or more non-backticks, a backtick; leftmost first, not overlapping)
// with a framed placeholder index, and returns the text and the spans. It
// matches exactly where reCode.ReplaceAllString would.
func liftCodeSpans(esc string) (string, []span) {
	i := strings.IndexByte(esc, '`')
	if i < 0 {
		return esc, nil
	}
	var b strings.Builder
	b.Grow(len(esc))
	var spans []span
	last := 0
	for i >= 0 && i < len(esc) {
		j := strings.IndexByte(esc[i+1:], '`')
		if j < 0 {
			break
		}
		if j == 0 {
			// "``": no span starts at i; the next backtick may open one.
			i++
			continue
		}
		end := i + 1 + j
		b.WriteString(esc[last:i])
		b.WriteString(codeSentinel)
		b.WriteString(strconv.Itoa(len(spans)))
		b.WriteString(codeSentinel)
		spans = append(spans, span{start: int32(i + 1), end: int32(end)})
		last = end + 1
		k := strings.IndexByte(esc[last:], '`')
		if k < 0 {
			break
		}
		i = last + k
	}
	if spans == nil {
		return esc, nil
	}
	b.WriteString(esc[last:])
	return b.String(), spans
}

// restoreSpans puts each code span back in place of its placeholder in one
// pass over s, writing <code>…</code> around its content in esc. Each
// placeholder occurs once and is restored once; anything else between NULs is
// copied through unchanged.
func restoreSpans(s, esc string, spans []span) string {
	if len(spans) == 0 {
		return s
	}
	if workProbe != nil {
		workProbe(len(s))
	}
	var b strings.Builder
	b.Grow(len(s) + 13*len(spans))
	restored := make([]bool, len(spans))
	for {
		j := strings.IndexByte(s, codeSentinel[0])
		if j < 0 {
			b.WriteString(s)
			return b.String()
		}
		b.WriteString(s[:j])
		rest := s[j+1:]
		k := strings.IndexByte(rest, codeSentinel[0])
		if k < 0 {
			b.WriteString(s[j:])
			return b.String()
		}
		if idx, err := strconv.Atoi(rest[:k]); err == nil && idx >= 0 && idx < len(spans) && !restored[idx] {
			restored[idx] = true
			sp := spans[idx]
			b.WriteString("<code>")
			b.WriteString(esc[sp.start:sp.end])
			b.WriteString("</code>")
			s = rest[k+1:]
			continue
		}
		// Not a placeholder: keep the NUL and rescan from the next byte.
		b.WriteByte(codeSentinel[0])
		s = rest
	}
}

// renderLink turns [text](url) into an anchor. Two layers of XSS defense:
//
//  1. Both text and url reach here ALREADY HTML-escaped, because inline()
//     escapes the whole line before any inline regex runs. So a url like
//     `https://a"onmouseover="x` arrives as `https://a&#34;onmouseover=&#34;x`
//     and cannot break out of the href attribute; injected text is inert too.
//  2. The URL scheme is checked against an ALLOWLIST (below); anything that is
//     not an explicitly-permitted scheme or a relative reference is dropped to
//     plain text, so javascript:/data:/vbscript: and unknown schemes never
//     become a live href. Rendered markdown is served same-origin, so this
//     matters.
func renderLink(match string) string {
	// match is reLink's "[text](url)": text holds no ']', so the first "](" ends
	// it, and the url runs to the closing ')'.
	k := strings.IndexByte(match, ']')
	text, u := match[1:k], match[k+2:len(match)-1]
	if !safeURL(u) {
		return text
	}
	return `<a href="` + u + `" rel="noopener noreferrer">` + text + `</a>`
}

// safeURL is an allowlist: it permits http/https/mailto absolute URLs and
// relative references (path, fragment, query), and rejects everything else —
// notably any other scheme. The input is already HTML-escaped and is decoded
// once, as the browser will, before any check.
//
// Two classes of character are refused before any classification, because a
// browser's URL parser reads them differently from the prefix checks below:
// a backslash is a path separator in http(s) URLs ("/\host" and "\\host"
// both resolve to another host), and tab, LF and CR are deleted wherever they
// appear ("/\t/host" becomes "//host"). Other control characters have no
// place in a link either. A web URL with userinfo ("https://trusted@evil") is
// refused too: it names one host and navigates to another.
func safeURL(u string) bool {
	// Judge the URL the browser will see: u is HTML-escaped, and the browser
	// decodes the attribute exactly once. Checking the escaped form would let
	// an entity hide a character ("&#34;" ends the authority scan at '#'
	// before a following '@').
	u = html.UnescapeString(u)
	if strings.ContainsRune(u, '\\') || hasControl(u) {
		return false
	}
	// Lowercased per ASCII byte: the checks below match ASCII schemes and
	// separators only, and full Unicode lowercasing can lengthen the text.
	lu := asciiLower(strings.TrimSpace(u))
	if lu == "" {
		return false
	}
	for _, scheme := range []string{"http://", "https://"} {
		if rest, ok := strings.CutPrefix(lu, scheme); ok {
			// The authority must follow the "//" directly: browsers skip
			// any extra slashes ("https:////a@b" is "https://a@b"), so an
			// empty authority would hide the userinfo check below.
			authority := rest
			if i := strings.IndexAny(rest, "/?#"); i >= 0 {
				authority = rest[:i]
			}
			return authority != "" && !strings.Contains(authority, "@")
		}
	}
	if strings.HasPrefix(lu, "mailto:") {
		return true
	}
	// Protocol-relative URLs ("//host/path") are external navigations, not
	// same-origin relative refs — reject them so a published markdown link cannot
	// silently redirect off-site (open-redirect / phishing). Must precede the
	// single-"/" relative allow below, which would otherwise match "//".
	if strings.HasPrefix(lu, "//") {
		return false
	}
	// Relative references are safe: they cannot carry an active-content scheme.
	if strings.HasPrefix(lu, "/") || strings.HasPrefix(lu, "#") || strings.HasPrefix(lu, "?") {
		return true
	}
	// Bare relative path (e.g. "page.html", "sub/page"): allow only if there is
	// no scheme-like colon before the first path separator.
	if colon := strings.IndexByte(lu, ':'); colon >= 0 {
		sep := strings.IndexAny(lu, "/#?")
		if sep == -1 || colon < sep {
			return false // looks like "scheme:..." → reject
		}
	}
	return true
}

// asciiLower lowercases the ASCII letters of s, leaving every other byte as
// it is, so the result is never longer than s.
func asciiLower(s string) string {
	for i := 0; i < len(s); i++ {
		if c := s[i]; c >= 'A' && c <= 'Z' {
			b := []byte(s)
			for j := i; j < len(b); j++ {
				if b[j] >= 'A' && b[j] <= 'Z' {
					b[j] += 'a' - 'A'
				}
			}
			return string(b)
		}
	}
	return s
}

// hasControl reports whether s contains a C0 or C1 control character or DEL.
func hasControl(s string) bool {
	for _, r := range s {
		if r < 0x20 || (r >= 0x7f && r <= 0x9f) {
			return true
		}
	}
	return false
}

// docHead returns the document head with css inlined. An explicit server theme
// (or a pinned/custom sheet) sets data-theme on <html>; a contract page with no
// server theme leaves the attribute off so the stylesheet's guarded
// prefers-color-scheme block follows the OS. When withInit is true (masthead
// pages, which carry the toggle) a tiny inline script runs before the body
// paints, applying a stored explicit choice from localStorage with no flash of
// the wrong theme; headerless renders ship no script at all (the reply flow
// depends on a JS-free document), so they follow the OS/server theme only.
//
// bodyClass, when non-empty, is set on <body>; an F page ("f ...") also gets
// the tree's pre-paint init script.
func docHead(css, titleText, themeName string, contract, withInit bool, bodyClass string) string {
	initial := themeName
	if initial == "" {
		initial = theme.Default
	}
	if titleText == "" {
		titleText = "Untitled"
	}
	htmlTag := `<html lang="en" data-theme="` + initial + `">`
	if contract && themeName == "" {
		// No explicit server theme: leave data-theme unset so the stylesheet's
		// guarded prefers-color-scheme block follows the OS with no JS at all;
		// the init script applies only a stored explicit choice.
		htmlTag = `<html lang="en">`
	}
	head := "<!DOCTYPE html>\n" + htmlTag + `
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="theme-color" content="` + theme.MetaColor(initial) + `">
<title>` + titleText + `</title>
<link rel="icon" type="image/svg+xml" href="` + demiplane.FaviconDataURI + `">
<style>` + css + `</style>
`
	if withInit {
		head += initThemeScript() + "\n"
	}
	body := "<body>\n"
	if bodyClass != "" {
		head += fInitScript + "\n"
		body = `<body class="` + bodyClass + `">` + "\n"
	}
	return head + "</head>\n" + body
}

// initThemeScript runs synchronously in <head> to apply a stored explicit
// theme choice before paint. Only "light"/"dark" values are honored; with no
// stored choice the markup's data-theme (the server --theme) or, when that is
// absent, the stylesheet's guarded prefers-color-scheme block decides, so the
// OS preference works even with JavaScript disabled.
func initThemeScript() string {
	return `<script>(function(){try{var s=localStorage.getItem('demiplane-theme');` +
		`if(s==='light'||s==='dark'){document.documentElement.setAttribute('data-theme',s);}}catch(e){}})();</script>`
}

